    public static string Kind(string lang, ScanKind k) => Get(lang, "kind." + k);
    public static string Level(string lang, AdviceLevel l) => Get(lang, "level." + l);
    public static string LevelHint(string lang, AdviceLevel l) => Get(lang, "levelHint." + l);
    public static string Media(string lang, MediaKind k) => Get(lang, "media." + k);
    public static string Cell(string lang, CellState s) => Get(lang, "state." + s);

