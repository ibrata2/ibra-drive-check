    public static string Get(string lang, string key)
    {
        var dict = lang == "en" ? En : Ar;
        if (dict.TryGetValue(key, out var v)) return v;
        if (En.TryGetValue(key, out var e)) return e;
        return key;
    }

    public static string Format(string lang, NoteItem n)
    {
        var tpl = Get(lang, n.Key);
        try
        {
            var args = n.Args.Select(a => (object)FormatArg(lang, n.Key, a)).ToArray();
            return string.Format(CultureInfo.InvariantCulture, tpl, args);
        }
        catch { return tpl; }
    }

    // أرقام البايتات في الملاحظات تعرض كأحجام مقروءة
    private static string FormatArg(string lang, string key, string a)
    {
        if (key is "note.estimateRange" or "note.wrapDetected" or "note.freeSpaceVerified" && long.TryParse(a, out var b))
            return Fmt.Bytes(b);
        return a;
    }

