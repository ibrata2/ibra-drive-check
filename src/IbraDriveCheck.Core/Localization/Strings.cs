public static class Fmt
{
    /// <summary>أحجام عشرية كما تكتبها الشركات على العلبة (1GB = 1,000,000,000 بايت).</summary>
    public static string Bytes(long bytes)
    {
        if (bytes < 0) bytes = 0;
        string[] u = { "B", "KB", "MB", "GB", "TB", "PB" };
        double v = bytes;
        int i = 0;
        while (v >= 1000 && i < u.Length - 1) { v /= 1000; i++; }
        string num = i == 0 ? v.ToString("0", CultureInfo.InvariantCulture)
            : v >= 100 ? v.ToString("0", CultureInfo.InvariantCulture)
            : v >= 10 ? v.ToString("0.#", CultureInfo.InvariantCulture)
            : v.ToString("0.##", CultureInfo.InvariantCulture);
        return $"{num} {u[i]}";
    }

    public static string Bytes(long? bytes, string lang) => bytes is long b ? Bytes(b) : Strings.Get(lang, "common.notAvailable");

    public static string Speed(double mbps) => mbps <= 0 ? "—" : mbps >= 100 ? $"{mbps:0} MB/s" : mbps >= 10 ? $"{mbps:0.0} MB/s" : $"{mbps:0.00} MB/s";

    public static string Duration(TimeSpan t) => t.TotalHours >= 1 ? $"{(int)t.TotalHours}:{t.Minutes:00}:{t.Seconds:00}" : $"{t.Minutes:00}:{t.Seconds:00}";

    public static string Hex(long v) => "0x" + v.ToString("X");

    public static string OrNA(string? s, string lang) => string.IsNullOrWhiteSpace(s) ? Strings.Get(lang, "common.notAvailable") : s;
}
